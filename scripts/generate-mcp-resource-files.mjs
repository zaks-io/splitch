import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(scriptDir, "..");
const outputPath = join(repoRoot, "apps/mcp-server/src/mcp-resource-files.generated.ts");

const contextMd = readFileSync(join(repoRoot, "CONTEXT.md"), "utf8");
const quickstartMd = readFileSync(join(repoRoot, "docs/spec/quickstart.md"), "utf8");

const contents = `// Generated by scripts/generate-mcp-resource-files.mjs — do not edit.
export const CONTEXT_MD = ${JSON.stringify(contextMd)};
export const QUICKSTART_MD = ${JSON.stringify(quickstartMd)};
`;

writeFileSync(outputPath, contents, "utf8");
const format = spawnSync("npx", ["biome", "format", "--write", outputPath], {
  cwd: repoRoot,
  stdio: "inherit",
});
if (format.status !== 0) {
  process.exit(format.status ?? 1);
}
console.log(`wrote ${outputPath}`);
