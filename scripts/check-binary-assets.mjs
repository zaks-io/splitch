#!/usr/bin/env node
// Pre-commit guard: no raster images in the repository, outside the brand dirs.
//
// Screenshots are build output. Playwright already writes them to the
// gitignored `test-results/` via `testInfo.outputPath()`, and a PR that needs
// to show one attaches it to the PR or the tracker issue, where it is reviewed
// once and then ages out. Committing them instead makes every clone carry the
// bytes forever: `docs/review/` reached 1.9MB of screenshots from four tickets
// before this guard existed, all of it dead within a week of the merge.
//
// Vector assets (.svg) are source and stay allowed.
//
// The brand mark is the one raster the product genuinely ships: a favicon and
// an apple-touch-icon have to be raster, and browsers fetch them from fixed
// paths in each Worker's asset bundle. Those paths are allowlisted below and
// nothing else is, so the guard still catches a screenshot dropped anywhere
// including elsewhere under `public/`. Regenerate the allowlisted files with
// `pnpm brand:assets`; do not hand-edit them.

import { execFileSync } from "node:child_process";

const RASTER_EXTENSIONS = [".png", ".jpg", ".jpeg", ".gif", ".webp", ".avif", ".bmp", ".ico"];

const ALLOWED_PATHS = [
  // The master every other size is derived from.
  "assets/brand/splitch-mark.png",
  // Per-app copies, written by scripts/generate-brand-assets.mjs.
  ...["apps/marketing", "apps/control-panel"].flatMap((app) => [
    `${app}/public/favicon.ico`,
    `${app}/public/apple-touch-icon.png`,
    `${app}/public/brand/splitch-mark.png`,
    `${app}/public/icon-192.png`,
    `${app}/public/icon-512.png`,
    `${app}/public/icon-maskable-512.png`,
  ]),
  // Only the public site is ever unfurled, so only it carries a social card.
  "apps/marketing/public/og-card.png",
];

function stagedFiles() {
  const records = execFileSync(
    "git",
    ["diff", "--cached", "--name-only", "-z", "--diff-filter=ACMR"],
    { encoding: "utf8" },
  );
  return records.split("\0").filter(Boolean);
}

const offenders = stagedFiles().filter(
  (file) =>
    RASTER_EXTENSIONS.some((ext) => file.toLowerCase().endsWith(ext)) &&
    !ALLOWED_PATHS.includes(file),
);

if (offenders.length > 0) {
  console.error(`\n✖ Binary-asset guard: ${offenders.length} raster image(s) staged.`);
  for (const file of offenders) {
    console.error(`  ${file}`);
  }
  console.error(
    "\nScreenshots and other rasters do not belong in git. Playwright writes\n" +
      "captures to the gitignored test-results/ directory — use\n" +
      "`testInfo.outputPath(name)`, never a hardcoded repo path. To show a\n" +
      "reviewer an image, attach it to the pull request or the tracker issue.\n" +
      "Source vectors (.svg) are unaffected. A new brand icon belongs in\n" +
      "assets/brand/, generated by `pnpm brand:assets` and allowlisted here.\n",
  );
  process.exit(1);
}
