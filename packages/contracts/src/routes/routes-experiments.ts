import { z } from "@hono/zod-openapi";
import { type ApiRouteContract, defineApiRoute } from "../openapi-route";
import {
  CreateMetricRequestSchema,
  MetricResponseSchema,
  PatchMetricRequestSchema,
} from "../resource-envelopes-account";
import {
  CreateExperimentRequestSchema,
  ExperimentResponseSchema,
  PatchExperimentRequestSchema,
  RunResponseSchema,
  StartRunRequestSchema,
  StartRunResponseSchema,
} from "../resource-envelopes-experiment";
import {
  AppParams,
  EnvParams,
  ExperimentParams,
  MetricParams,
  RunEndParams,
  RunParams,
} from "./route-shapes";

/**
 * Experiment draft/start lifecycle, Experiment Run reads + end, and Metric CRUD.
 * Control Plane API Worker; per-Environment (ADR-0027) for experiments/runs.
 * Endpoint canon: endpoints-experiment-run.md, endpoints-metric.md.
 */

const OWNER = "control-plane-api" as const;
const AUTH = "control-plane-token" as const;
const RATE = "control-plane-actor" as const;

const ExperimentListResponse = z.object({ items: z.array(ExperimentResponseSchema) });
const RunListResponse = z.object({ items: z.array(RunResponseSchema) });
const MetricListResponse = z.object({ items: z.array(MetricResponseSchema) });
const DeletedResponse = z.object({ deleted: z.literal(true) });

const APPROVAL_WRITE_ERRORS = [
  "APPROVAL_REVIEW_REQUIRED",
  "APPROVAL_REVIEW_FORBIDDEN",
  "APPROVAL_REQUEST_STALE",
  "APPROVAL_REQUEST_RESOLVED",
  "APPROVAL_APPLICATION_FAILED",
  "IDEMPOTENCY_KEY_CONFLICT",
] as const;

export const experimentRoutes = [
  defineApiRoute({
    operationId: "experiments_list",
    owner: OWNER,
    method: "GET",
    path: "/apps/:appId/envs/:environmentId/experiments",
    summary: "List Experiments in an Environment.",
    request: { params: EnvParams },
    response: ExperimentListResponse,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: ["APP_NOT_FOUND", "FORBIDDEN"],
  }),
  defineApiRoute({
    operationId: "experiments_create",
    owner: OWNER,
    method: "POST",
    path: "/apps/:appId/envs/:environmentId/experiments",
    summary: "Create an Experiment draft.",
    request: { params: EnvParams, body: CreateExperimentRequestSchema },
    response: ExperimentResponseSchema,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "optional",
    errors: [
      "APP_NOT_FOUND",
      "FLAG_NOT_FOUND",
      "VARIANT_NOT_AVAILABLE",
      "FORBIDDEN",
      "VALIDATION_ERROR",
    ],
  }),
  defineApiRoute({
    operationId: "experiments_get",
    owner: OWNER,
    method: "GET",
    path: "/apps/:appId/envs/:environmentId/experiments/:experimentId",
    summary: "Get an Experiment (includes live Run id, draft config).",
    request: { params: ExperimentParams },
    response: ExperimentResponseSchema,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: ["EXPERIMENT_NOT_FOUND", "FORBIDDEN"],
  }),
  defineApiRoute({
    operationId: "experiments_update",
    owner: OWNER,
    method: "PATCH",
    path: "/apps/:appId/envs/:environmentId/experiments/:experimentId",
    summary: "Edit an Experiment (assignment edits gated by RUN_FROZEN / DECISION_LOCKED).",
    request: { params: ExperimentParams, body: PatchExperimentRequestSchema },
    response: ExperimentResponseSchema,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: [
      "EXPERIMENT_NOT_FOUND",
      "FORBIDDEN",
      "RUN_FROZEN",
      "DECISION_LOCKED",
      "ALLOCATION_INVALID",
      "VALIDATION_ERROR",
    ],
  }),
  defineApiRoute({
    operationId: "experiments_start",
    owner: OWNER,
    method: "POST",
    path: "/apps/:appId/envs/:environmentId/experiments/:experimentId/start",
    summary: "Start the draft as a new Run; ends any running Run (Policy-gated).",
    request: { params: ExperimentParams, body: StartRunRequestSchema },
    response: StartRunResponseSchema,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "required",
    errors: [
      "EXPERIMENT_NOT_FOUND",
      "FORBIDDEN",
      "EXPERIMENT_RUNNING",
      "EXPERIMENT_NO_DRAFT",
      "ALLOCATION_INVALID",
      "VARIANT_NOT_AVAILABLE",
      ...APPROVAL_WRITE_ERRORS,
      "VALIDATION_ERROR",
    ],
  }),
  defineApiRoute({
    operationId: "experiments_delete",
    owner: OWNER,
    method: "DELETE",
    path: "/apps/:appId/envs/:environmentId/experiments/:experimentId",
    summary: "Delete an Experiment and its D1 Runs (blocked while a Run is running).",
    request: { params: ExperimentParams },
    response: DeletedResponse,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: ["EXPERIMENT_NOT_FOUND", "FORBIDDEN", "EXPERIMENT_RUNNING"],
  }),
  defineApiRoute({
    operationId: "runs_list",
    owner: OWNER,
    method: "GET",
    path: "/apps/:appId/envs/:environmentId/experiments/:experimentId/runs",
    summary: "List an Experiment's Runs (newest first).",
    request: { params: ExperimentParams },
    response: RunListResponse,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: ["EXPERIMENT_NOT_FOUND", "FORBIDDEN"],
  }),
  defineApiRoute({
    operationId: "runs_get",
    owner: OWNER,
    method: "GET",
    path: "/apps/:appId/envs/:environmentId/experiments/:experimentId/runs/:runId",
    summary: "Get a full Run (frozen assignment + measurement config + status).",
    request: { params: RunParams },
    response: RunResponseSchema,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: ["RUN_NOT_FOUND", "FORBIDDEN"],
  }),
  defineApiRoute({
    operationId: "runs_end",
    owner: OWNER,
    method: "POST",
    path: "/apps/:appId/envs/:environmentId/runs/:runId/end",
    summary: "End a running Run.",
    request: { params: RunEndParams, body: z.object({ reason: z.string().optional() }).optional() },
    response: RunResponseSchema,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: ["RUN_NOT_FOUND", "FORBIDDEN", "RUN_NOT_RUNNING"],
  }),
  defineApiRoute({
    operationId: "metrics_list",
    owner: OWNER,
    method: "GET",
    path: "/apps/:appId/metrics",
    summary: "List Metrics in an App.",
    request: { params: AppParams },
    response: MetricListResponse,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: ["APP_NOT_FOUND", "FORBIDDEN"],
  }),
  defineApiRoute({
    operationId: "metrics_create",
    owner: OWNER,
    method: "POST",
    path: "/apps/:appId/metrics",
    summary: "Create a Metric (binomial, count, revenue, ratio, guardrail).",
    request: { params: AppParams, body: CreateMetricRequestSchema },
    response: MetricResponseSchema,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "optional",
    errors: ["APP_NOT_FOUND", "FORBIDDEN", "VALIDATION_ERROR"],
  }),
  defineApiRoute({
    operationId: "metrics_get",
    owner: OWNER,
    method: "GET",
    path: "/apps/:appId/metrics/:metricId",
    summary: "Get a Metric.",
    request: { params: MetricParams },
    response: MetricResponseSchema,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: ["METRIC_NOT_FOUND", "FORBIDDEN"],
  }),
  defineApiRoute({
    operationId: "metrics_update",
    owner: OWNER,
    method: "PATCH",
    path: "/apps/:appId/metrics/:metricId",
    summary: "Update a Metric (decision-valid edits gated by DECISION_LOCKED).",
    request: { params: MetricParams, body: PatchMetricRequestSchema },
    response: MetricResponseSchema,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: ["METRIC_NOT_FOUND", "FORBIDDEN", "DECISION_LOCKED", "VALIDATION_ERROR"],
  }),
  defineApiRoute({
    operationId: "metrics_delete",
    owner: OWNER,
    method: "DELETE",
    path: "/apps/:appId/metrics/:metricId",
    summary: "Delete a Metric (blocked if referenced by a running Experiment).",
    request: { params: MetricParams },
    response: DeletedResponse,
    auth: AUTH,
    rateLimit: RATE,
    idempotency: "none",
    errors: ["METRIC_NOT_FOUND", "FORBIDDEN", "EXPERIMENT_RUNNING"],
  }),
] as const satisfies readonly ApiRouteContract[];
